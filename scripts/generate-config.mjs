import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, '..');
const envPath = path.join(rootDir, '.env');
const outPath = path.join(__dirname, 'config.js');

function parseEnvFile(filePath) {
  if (!fs.existsSync(filePath)) return {};
  const out = {};
  const lines = fs.readFileSync(filePath, 'utf8').split(/\r?\n/);
  for (const raw of lines) {
    const line = raw.trim();
    if (!line || line.startsWith('#')) continue;
    const eq = line.indexOf('=');
    if (eq === -1) continue;
    const key = line.slice(0, eq).trim();
    let val = line.slice(eq + 1).trim();
    if ((val.startsWith('"') && val.endsWith('"')) || (val.startsWith("'") && val.endsWith("'"))) {
      val = val.slice(1, -1);
    }
    out[key] = val;
  }
  return out;
}

const fileEnv = parseEnvFile(envPath);
const readVar = (name, fallback = '') => process.env[name] ?? fileEnv[name] ?? fallback;

// Guard against accidentally exposing a service_role key in client config
const anonKey = readVar('SUPABASE_ANON_KEY', '');
if (anonKey.includes('service_role')) {
  throw new Error('Refusing to write service_role key into public frontend scripts/config.js');
}

const config = {
  SUPABASE_URL: readVar('SUPABASE_URL', ''),
  SUPABASE_ANON_KEY: anonKey,
  COLLEGE_NAME: readVar('COLLEGE_NAME', 'College NCC Unit'),
  NCC_UNIT: readVar('NCC_UNIT', 'National Cadet Corps — College Unit'),
  EVENT_DATES: readVar('EVENT_DATES', 'Two-Day College NCC Event (Dates TBA)'),
  EVENT_VENUE: readVar('EVENT_VENUE', 'College Parade Ground & Auditorium'),
  CONTACT_EMAIL: readVar('CONTACT_EMAIL', 'ncc.event@college.edu'),
  CONTACT_PHONE: readVar('CONTACT_PHONE', '+91 90000 00000'),
  SIGNATORY_NAME: readVar('SIGNATORY_NAME', 'Associate NCC Officer (ANO)'),
  SIGNATORY_TITLE: readVar('SIGNATORY_TITLE', 'Event Convenor, NCC Unit'),
  RAZORPAY_KEY_ID: readVar('RAZORPAY_KEY_ID', ''),
  DEMO_PAYMENT_MODE: readVar('DEMO_PAYMENT_MODE', 'true').toLowerCase() !== 'false'
};

const content = `// Auto-generated by scripts/generate-config.mjs. Do not put secrets here.\nwindow.NCC_CONFIG = ${JSON.stringify(config, null, 2)};\n`;
fs.writeFileSync(outPath, content, 'utf8');
console.log('Generated scripts/config.js successfully.');
